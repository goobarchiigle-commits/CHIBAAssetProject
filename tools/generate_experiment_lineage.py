"""
tools/generate_experiment_lineage.py
Generate docs/EXPERIMENT_LINEAGE.md with Mermaid ancestry diagram.

Reads state/experiment_registry.json and builds a parent→child graph.

Usage:
    python tools/generate_experiment_lineage.py
    python tools/generate_experiment_lineage.py --output docs/EXPERIMENT_LINEAGE.md
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import datetime, timezone, timedelta
from pathlib import Path

REPO_ROOT   = Path(__file__).resolve().parent.parent
DOCS_DIR    = REPO_ROOT / "docs"
OUTPUT_FILE = DOCS_DIR / "EXPERIMENT_LINEAGE.md"

JST = timezone(timedelta(hours=9))

sys.path.insert(0, str(REPO_ROOT))

logging.basicConfig(
    level=logging.INFO,
    format="[LINEAGE] %(levelname)s %(message)s",
)
logger = logging.getLogger(__name__)


def _load_experiments() -> list[dict]:
    from src.governance.experiment import ExperimentRegistry
    registry = ExperimentRegistry()
    return [m.to_dict() for m in registry.list_all()]


def _build_mermaid(experiments: list[dict]) -> str:
    lines = ["graph TD"]
    for exp in experiments:
        eid    = exp["experiment_id"]
        sid    = exp.get("strategy_id", "?")
        mode   = exp.get("runtime_mode", "?")
        seed   = exp.get("seed", "?")
        label  = f"{eid}\\n{sid}\\nmode={mode} seed={seed}"
        lines.append(f'    {eid}["{label}"]')

    for exp in experiments:
        eid    = exp["experiment_id"]
        parent = exp.get("parent_experiment")
        if parent:
            lines.append(f"    {parent} --> {eid}")

    return "\n".join(lines)


def _strategy_summary(experiments: list[dict]) -> dict[str, list[str]]:
    by_strategy: dict[str, list[str]] = {}
    for exp in experiments:
        sid = exp.get("strategy_id", "unknown")
        by_strategy.setdefault(sid, []).append(exp["experiment_id"])
    return by_strategy


def generate_lineage_doc(experiments: list[dict]) -> str:
    now    = datetime.now(JST).strftime("%Y-%m-%dT%H:%M:%S%z")
    count  = len(experiments)
    mermaid = _build_mermaid(experiments)
    by_strat = _strategy_summary(experiments)

    strat_table_rows = "\n".join(
        f"| {sid} | {len(eids)} |"
        for sid, eids in sorted(by_strat.items())
    )

    exp_rows = "\n".join(
        "| {eid} | {sid} | {mode} | {seed} | {parent} | {created} |".format(
            eid=e["experiment_id"],
            sid=e.get("strategy_id", ""),
            mode=e.get("runtime_mode", ""),
            seed=str(e.get("seed", "")),
            parent=e.get("parent_experiment") or "—",
            created=e.get("created_at", "")[:10],
        )
        for e in experiments
    ) or "_No experiments registered._"

    return f"""# EXPERIMENT_LINEAGE.md — CHIBAAssetProject
> **Generated**: {now}
> Auto-generated by `tools/generate_experiment_lineage.py`. Do not edit manually.

---

## Summary

- Total experiments: **{count}**
- Strategies covered: **{len(by_strat)}**

| Strategy | Experiment count |
|----------|-----------------|
{strat_table_rows or "| — | 0 |"}

---

## Ancestry Graph

```mermaid
{mermaid}
```

---

## Experiment Index

| ID | Strategy | Mode | Seed | Parent | Created |
|----|----------|------|------|--------|---------|
{exp_rows}

---

## How to Add an Experiment

```python
from src.governance.experiment import build_manifest, ExperimentRegistry

manifest = build_manifest(
    strategy_id="my_strategy",
    runtime_mode="paper",
    seed=42,
    config_hash="...",
    dataset_hash="...",
    parent_experiment="exp_20260101_abc12345",
)
ExperimentRegistry().register(manifest)
```

```bash
# Regenerate this file:
python tools/generate_experiment_lineage.py
```
"""


def _cli() -> None:
    parser = argparse.ArgumentParser(
        description="Generate docs/EXPERIMENT_LINEAGE.md"
    )
    parser.add_argument(
        "--output", default=str(OUTPUT_FILE),
        help="Output file path",
    )
    args = parser.parse_args()

    experiments = _load_experiments()
    doc = generate_lineage_doc(experiments)

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8")
    logger.info("Generated %s (%d experiments)", out, len(experiments))


if __name__ == "__main__":
    _cli()
