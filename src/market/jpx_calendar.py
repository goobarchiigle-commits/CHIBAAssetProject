    def __init__(self):
        self._holidays: set[pd.Timestamp] = {
            pd.Timestamp(d) for d in self._HOLIDAY_STRINGS
        }

    def is_trading_day(self, d) -> bool:
        d = pd.Timestamp(d)
        if d.weekday() >= 5:       # 土日
            return False
        if d in self._holidays:    # 祝日・年末年始
            return False
        return True

    def trading_days_between(self, start, end) -> int:
        """start と end の間の営業日数（両端含む）。"""
        days = pd.date_range(start, end, freq="D")
        return sum(self.is_trading_day(d) for d in days)

    def add_trading_days(self, start, n: int) -> pd.Timestamp:
        """start から n 営業日後の日付を返す。"""
        d = pd.Timestamp(start)
        count = 0
        while count < n:
            d += pd.Timedelta(days=1)
            if self.is_trading_day(d):
                count += 1
        return d

    def prev_trading_day(self, d) -> pd.Timestamp:
        """直前の営業日（d 自身が営業日でも前日を返す）。"""
        d = pd.Timestamp(d) - pd.Timedelta(days=1)
        while not self.is_trading_day(d):
            d -= pd.Timedelta(days=1)
        return d
